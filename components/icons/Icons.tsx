// Maps an IconKey (data) to its glyph (presentation) — keeps
// ToolNode / ActionCardData free of any rendering concerns.
export function ToolIcon({
  icon,
  className,
}: {
  icon: IconKey;
  className?: string;
}) {
  switch (icon) {
    case "web":
      return <GlobeIcon className={className} />;
    case "research":
      return <MicroscopeIcon className={className} />;
    case "image":
      return <ImageIcon className={className} />;
    case "writer":
      return <PenIcon className={className} />;
    case "rag":
      return <DatabaseIcon className={className} />;
    case "upload":
      return <UploadIcon className={className} />;
    default:
      return null;
  }
}
